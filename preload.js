'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  platform: process.platform,
  vaultRead: () => ipcRenderer.invoke('vault:read'),
  vaultWrite: (text) => ipcRenderer.invoke('vault:write', text),
  vaultDelete: () => ipcRenderer.invoke('vault:delete'),
  win: (action) => ipcRenderer.send('win:' + action),
  winDrag: (dx, dy) => ipcRenderer.send('win:dragMove', dx, dy),
  onWinState: (cb) => ipcRenderer.on('win:state', (_e, s) => cb(s)),
  onMenu: (cb) => ipcRenderer.on('menu:cmd', (_e, cmd) => cb(cmd)),
  copy: (text, clearAfterMs) => ipcRenderer.invoke('clip:write', text, clearAfterMs || 0),
  clipClearIf: (text) => ipcRenderer.invoke('clip:clearIf', text),
  protect: (on) => ipcRenderer.invoke('win:protect', on),
  onHidden: (fn) => ipcRenderer.on('win:hidden', () => fn()),
  hibpRange: (prefix) => ipcRenderer.invoke('hibp:range', prefix),
  cardPdf: (html, name) => ipcRenderer.invoke('card:pdf', html, name),
  cardPrint: (html) => ipcRenderer.invoke('card:print', html),
  logExport: (rows) => ipcRenderer.invoke('log:export', rows),
  excelExport: (rows) => ipcRenderer.invoke('excel:export', rows),
  excelTemplate: (licenses) => ipcRenderer.invoke('excel:template', licenses),
  excelImport: () => ipcRenderer.invoke('excel:import'),
  backupExport: (text) => ipcRenderer.invoke('backup:export', text),
  backupImport: () => ipcRenderer.invoke('backup:import'),
  appInfo: () => ipcRenderer.invoke('app:info'),
  kdfScrypt: (pw, salt, params) => ipcRenderer.invoke('kdf:scrypt', pw, salt, params),
  smsCheck: (cfg) => ipcRenderer.invoke('sms:check', cfg),
  smsSend: (cfg, to, text) => ipcRenderer.invoke('sms:send', cfg, to, text),
  smsCompose: (to) => ipcRenderer.invoke('sms:compose', to),
  msLoginStart: (cfg) => ipcRenderer.invoke('ms:loginStart', cfg),
  msLoginWait: () => ipcRenderer.invoke('ms:loginWait'),
  msLoginCancel: () => ipcRenderer.invoke('ms:loginCancel'),
  msSync: (cfg) => ipcRenderer.invoke('ms:sync', cfg),
  msSetPassword: (cfg, msId, pw, force) => ipcRenderer.invoke('ms:setPassword', cfg, msId, pw, force),
  msForgetWrite: () => ipcRenderer.invoke('ms:forgetWrite'),
  msOpenLogin: (uri) => ipcRenderer.invoke('ms:openLogin', uri),
  showInFolder: (p) => ipcRenderer.invoke('shell:show', p),
  openUrl: (u) => ipcRenderer.invoke('shell:openUrl', u)
});
